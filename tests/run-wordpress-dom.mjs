import assert from 'node:assert/strict';
import {parseHTML} from './dom-runtime/node_modules/linkedom/esm/index.js';
import {mountWebsitePreparation} from '../app/assets/website-domain.mjs';
const {document,window}=parseHTML('<html><head></head><body><section id="page"><div class="package-module-slot"></div></section></body></html>');
window.HTMLElement.prototype.scrollIntoView=function(){};
const page=document.getElementById('page');
let calls=0;
const view=mountWebsitePreparation({page,getOwnerId:async()=>'owner',stylesheetUrl:'/style.css',request:async()=>{calls++;return {ok:true,state:'preparation',revision:0,draft:null,shop_url:null,can_publish:false};},wordpressRequest:async()=>{throw Error('no target');}});
assert.equal(page.querySelectorAll('[data-website-overview] > button').length,3,'keep three compact overview entries');
assert.equal(page.querySelectorAll('[data-website-view]').length,4,'WordPress uses its own view');
assert.equal(page.querySelector('[data-website-view="connection"]').hidden,true);
page.querySelector('[data-website-open="website"]').click();
assert.equal(page.querySelector('[data-website-view="website"]').hidden,false);
page.querySelector('[data-wp-entry]').click();
assert.equal(page.querySelector('[data-website-view="connection"]').hidden,false);
assert.equal(page.querySelector('[data-website-view="website"]').hidden,true);
assert.equal(page.querySelector('[data-wp-start]').disabled,true,'no target cannot start a connection');
assert.equal(calls,0,'inactive dashboard must not load customer data');
page.querySelector('[data-website-back]').click();assert.equal(page.querySelector('[data-website-overview]').hidden,false);
view.destroy();assert(page.querySelector('.package-module-slot'));assert.equal(page.querySelector('[data-wordpress-panel]'),null);
console.log('WordPress dashboard DOM checks passed: compact overview, separate view, disabled missing target, teardown');
